#!/usr/bin/env python3
"""Rebuild the dated official/community citation comparison offline.

All inputs are versioned. --check compares generated bytes without writing.
Paper groups group entries by their highest-count reviewed paper, not identity.
"""
import argparse
from collections import Counter, defaultdict
import copy
import csv
import hashlib
import io
import json
from pathlib import Path
from urllib.parse import quote

ROOT = Path(__file__).resolve().parents[1]
HERE = ROOT / 'research/catalog-citations-20261030'
SCOPES = {'global','regional','mixed','unclear'}


def read(name):
    return json.loads((HERE / name).read_text())


def norm(doi):
    return doi.lower().removeprefix('https://doi.org/').removeprefix('http://doi.org/')


def markdown_url(url):
    return quote(url, safe=":/?=&%#")


def sort_rows(rows, field='max_paper_citations'):
    return sorted(rows,key=lambda r:(r[field] is None,-(r[field] or 0),r['id']))


def select_works(ids, works, role):
    result = []
    for wid in sorted(set(ids)):
        if wid not in works:
            continue
        w = works[wid]['work']
        if role == 'paper':
            assert w['type'] != 'dataset', f'Data release entered paper ranking: {wid} {w["title"]}'
        assert type(w['cited_by_count']) is int and w['cited_by_count'] >= 0
        result.append(wid)
    return sorted(result,key=lambda wid:(-works[wid]['work']['cited_by_count'],wid))


def score(row, paper_ids, data_ids, works, missing_papers, missing_data, unresolved):
    paper_ids=select_works(paper_ids,works,'paper');data_ids=select_works(data_ids,works,'data')
    assert not set(paper_ids) & set(data_ids), f'Mixed roles: {row["id"]}'
    p=works[paper_ids[0]]['work'] if paper_ids else {}
    d=works[data_ids[0]]['work'] if data_ids else {}
    row.update(paper_work_ids=paper_ids,data_work_ids=data_ids,
        max_paper_citations=p.get('cited_by_count'),top_paper_title=p.get('title'),
        top_paper_doi=p.get('doi'),top_paper_openalex_id=p.get('id'),top_paper_year=p.get('publication_year'),
        max_data_doi_citations=d.get('cited_by_count'),top_data_doi=d.get('doi'),
        missing_paper_references=sorted(set(missing_papers)),missing_data_references=sorted(set(missing_data)),
        unresolved_paper_titles=sorted(set(unresolved)),
        paper_count_status=('partial' if missing_papers or unresolved else 'matched') if p else 'unknown',
        citations_2025=next((x['cited_by_count'] for x in p.get('counts_by_year',[]) if x['year']==2025),None),
        citations_2026_ytd=next((x['cited_by_count'] for x in p.get('counts_by_year',[]) if x['year']==2026),None))
    return row


def review_inputs(entries):
    groups={g['id']:g for g in read('reference-groups.json')}
    reviews=[g for shard in 'abc' for g in read(f'review-{shard}.json')]
    assert len(reviews)==len(groups)==len({g['id'] for g in reviews})
    assert {g['id'] for g in reviews}==set(groups)
    seen=[]
    for r in reviews:
        assert not set(r['paper_dois']) & set(r['data_dois']),r['id']
        assert all(d==norm(d) for d in r['paper_dois']+r['data_dois']),r['id']
        assert {e['id'] for e in r['entries']}=={e['id'] for e in groups[r['id']]['entries']},r['id']
        for e in r['entries']:
            assert e['geographic_scope'] in SCOPES and e['region'] and e['scope_note']
            seen.append(e['id'])
    assert len(seen)==len(set(seen))==len(entries)
    return {g['id']:g for g in reviews}


def correction_applies(correction, entry):
    # An explicit list narrows a shared reference group, including the empty group.
    if 'entry_ids' in correction:
        return entry['id'] in correction['entry_ids']
    return correction.get('group_id') == entry['review_group']


def official_rows(entries,reviews,works,doi_ids,matches,corrections):
    out=[]
    for e in entries:
        review=copy.deepcopy(reviews[e['review_group']])
        geography=next(g for g in review['entries'] if g['id']==e['id'])
        papers=set(review['paper_dois']);data=set(review['data_dois'])
        title_matches=[m for m in matches if m['group_id']==e['review_group']]
        resolved_titles={m['query_title'] for m in title_matches}
        unresolved={t['title'] for t in review['unresolved_titles']} - resolved_titles
        supplements=[]
        for c in corrections:
            if not correction_applies(c,e):
                continue
            papers=(papers | set(c.get('add_paper_dois',[]))) - set(c.get('remove_paper_dois',[]))
            data=(data | set(c.get('add_data_dois',[]))) - set(c.get('remove_data_dois',[]))
            unresolved -= set(c.get('resolved_titles',[]))
            for k in ['citation_scope','citation_scope_note']:
                if k in c:review[k]=c[k]
            for k in ['geographic_scope','region','scope_note']:
                if k in c:geography[k]=c[k]
            supplements.append(c)
        assert not papers & data,e['id']
        paper_ids=[doi_ids[d] for d in papers if d in doi_ids] + [m['work_id'] for m in title_matches]
        data_ids=[doi_ids[d] for d in data if d in doi_ids]
        missing_p=[d for d in papers if d not in doi_ids]+[m['work_id'] for m in title_matches if m['work_id'] not in works]
        missing_d=[d for d in data if d not in doi_ids]
        row={'id':'official:'+e['id'],'catalog':'official','catalog_id':e['id'],'title':e['title'],
             'url':e['catalog_url'],'geographic_scope':geography['geographic_scope'],'region':geography['region'],
             'scope_note':geography['scope_note'],'deprecated':e['deprecated'],'review_group':e['review_group'],
             'citation_scope':review['citation_scope'],'citation_scope_note':review['citation_scope_note'],
             'reviewed_paper_dois':sorted(papers),'reviewed_data_dois':sorted(data),
             'supplemental_reference_review':supplements}
        out.append(score(row,paper_ids,data_ids,works,missing_p,missing_d,unresolved))
    return sort_rows(out)


def community_rows(works,doi_ids):
    old=json.loads((ROOT/'research/citations/rankings.json').read_text())
    out=[]
    for e in old:
        paper_ids=[p['work']['id'] for p in e['papers']]
        data_ids=[p['work']['id'] for p in e['data_dois']]
        paper_ids += [doi_ids[d] for d in e['unmatched_paper_dois'] if d in doi_ids]
        data_ids += [doi_ids[d] for d in e['unmatched_data_dois'] if d in doi_ids]
        missing_p=[d for d in e['unmatched_paper_dois'] if d not in doi_ids]+[w for w in paper_ids if w not in works]
        missing_d=[d for d in e['unmatched_data_dois'] if d not in doi_ids]+[w for w in data_ids if w not in works]
        row={'id':'community:'+e['slug'],'catalog':'community','catalog_id':e['slug'],'title':e['title'],
             'url':e['community_url'],'geographic_scope':e['geographic_scope'],
             'region':'Global' if e['geographic_scope']=='global' else e['scope_note'],
             'scope_note':e['scope_note'],'deprecated':None,
             'citation_scope':e['citation_scope'],'citation_scope_note':e['citation_scope_note'],
             'identity_source':'../citations/rankings.json; original reviewed identities retained',
             'publication_route':e['publication_route']}
        out.append(score(row,paper_ids,data_ids,works,missing_p,missing_d,e['unresolved_paper_titles']))
    assert len(out)==363
    return sort_rows(out)


def paper_groups(rows):
    groups={}
    for row in rows:
        if row['top_paper_openalex_id'] is None:continue
        wid=row['top_paper_openalex_id']
        group=groups.setdefault(wid,{'id':wid,'top_paper_title':row['top_paper_title'],
            'top_paper_doi':row['top_paper_doi'],'max_paper_citations':row['max_paper_citations'],
            'top_paper_year':row['top_paper_year'],'entries':[]})
        assert group['max_paper_citations']==row['max_paper_citations']
        group['entries'].append({k:row[k] for k in ['id','catalog','catalog_id','title','url','geographic_scope','region','deprecated','citation_scope']})
    for group in groups.values():
        group['entries'].sort(key=lambda e:(e['deprecated'] is True,e['id']))
        group['entry_count']=len(group['entries'])
        group['catalogs']=sorted({e['catalog'] for e in group['entries']})
        group['regions']=sorted({e['region'] for e in group['entries']})
        group['interpretation']='Shared highest-count paper; not a dataset identity merge or a sum.'
    return sort_rows(list(groups.values()))


def overlaps(official,community):
    bywork=defaultdict(list)
    for c in community:
        for wid in c['paper_work_ids']:bywork[wid].append(c['catalog_id'])
    pairs={}
    for o in official:
        for wid in o['paper_work_ids']:
            for slug in bywork[wid]:
                pair=pairs.setdefault((o['catalog_id'],slug),{'official_id':o['catalog_id'],'community_slug':slug,'shared_paper_ids':[],'shared_asset_ids':[]})
                pair['shared_paper_ids'].append(wid)
    ids={o['catalog_id'] for o in official}
    families=json.loads((ROOT/'research/gee-community-audit-20261029/families.json').read_text())
    for family in families:
        for asset in sorted(set(family['asset_ids']) & ids):
            pair=pairs.setdefault((asset,family['slug']),{'official_id':asset,'community_slug':family['slug'],'shared_paper_ids':[],'shared_asset_ids':[]})
            pair['shared_asset_ids'].append(asset)
    out=[]
    for key,pair in sorted(pairs.items()):
        pair['relations']=(['shared_paper'] if pair['shared_paper_ids'] else [])+(['shared_asset_reference'] if pair['shared_asset_ids'] else [])
        pair['identity_status']='candidate_only_not_equivalence'
        pair['note']='A shared paper can cover variants; an asset in a community page can be a dependency or example. Inspect primary product/version before merging.'
        out.append(pair)
    return out


FIELDS=['rank','id','title','geographic_scope','region','deprecated','max_paper_citations','paper_count_status','top_paper_year','top_paper_title','top_paper_doi','top_paper_openalex_id','citations_2025','citations_2026_ytd','citation_scope','citation_scope_note','max_data_doi_citations','top_data_doi','url']


def csv_table(rows,fields=FIELDS,score_key='max_paper_citations'):
    stream=io.StringIO(newline='');writer=csv.DictWriter(stream,fields,lineterminator='\n');writer.writeheader()
    previous=object();rank=0
    for pos,row in enumerate(rows,1):
        if row.get(score_key) is not None and row[score_key]!=previous:rank=pos;previous=row[score_key]
        values={k:row.get(k) for k in fields}
        if 'rank' in fields:values['rank']=rank if row.get(score_key) is not None else ''
        values={k:('; '.join(str(x) for x in v) if isinstance(v,list) else v) for k,v in values.items()}
        writer.writerow(values)
    return stream.getvalue()


def coverage(rows):
    return {'entries':len(rows),'paper_count':sum(r['max_paper_citations'] is not None for r in rows),
            'data_doi_count':sum(r['max_data_doi_citations'] is not None for r in rows),
            'no_count':sum(r['max_paper_citations'] is None and r['max_data_doi_citations'] is None for r in rows),
            'paper_status':dict(sorted(Counter(r['paper_count_status'] for r in rows).items())),
            'scope':dict(sorted(Counter(r['geographic_scope'] for r in rows).items())),
            'deprecated':sum(r['deprecated'] is True for r in rows)}


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    entries=read('official-entries.json');reviews=review_inputs(entries);works=read('openalex-works.json')
    doi_ids={d:r['work_id'] for d,r in read('doi-resolution.json').items() if r['status']=='matched'}
    for wid,o in works.items():
        if o['work'].get('doi'):doi_ids.setdefault(norm(o['work']['doi']),wid)
        receipt=read(o['response_path'])
        assert o['work'] in receipt['response']['results']
        assert hashlib.sha256(json.dumps(receipt['response'],sort_keys=True,ensure_ascii=False).encode()).hexdigest()==receipt['response_normalized_sha256']
    matches=read('title-matches.json');corrections=read('reference-corrections.json')
    for m in matches:
        capture=read('identity-searches.json')[m['query_title']]
        assert m['work_id'] in {w['id'] for w in capture['response']['results']}
        assert m['basis']
    official=official_rows(entries,reviews,works,doi_ids,matches,corrections)
    community=community_rows(works,doi_ids)
    combined=sort_rows(official+community)
    overlap=overlaps(official,community)
    files={}
    def put_json(name,obj):files[name]=json.dumps(obj,indent=2,ensure_ascii=False)+'\n'
    times=[o['retrieved_at'] for o in works.values()]
    summary={'study_id':'official-and-community-20261030','provider':'OpenAlex','metric':'max reviewed associated paper cited_by_count; never sum',
             'retrieval_started_utc':min(times),'retrieval_ended_utc':max(times),'observed_works':len(works),
             'official':coverage(official),'community':coverage(community),'combined':coverage(combined),
             'overlap_candidate_pairs':len(overlap),'shared_paper_pairs':sum(bool(r['shared_paper_ids']) for r in overlap),
             'shared_asset_reference_pairs':sum(bool(r['shared_asset_ids']) for r in overlap),
             'limitations':read('methodology.json')['limitations']}
    for catalog,rows in [('official',official),('community',community),('combined',combined)]:
        put_json(catalog+'-rankings.json',rows)
        views={'all':rows,'global':[r for r in rows if r['geographic_scope']=='global']}
        if catalog!='community':
            views['active']=[r for r in rows if r['deprecated'] is not True]
            views['active-global']=[r for r in views['active'] if r['geographic_scope']=='global']
        for name,subset in views.items():
            files[f'ranking-{catalog}-{name}.csv']=csv_table(subset)
            groups=paper_groups(subset)
            put_json(f'groups-{catalog}-{name}.json',groups)
            files[f'groups-{catalog}-{name}.csv']=csv_table(groups,['rank','id','top_paper_title','top_paper_doi','max_paper_citations','top_paper_year','entry_count','catalogs','regions'])
        data=sort_rows([r for r in rows if r['max_data_doi_citations'] is not None],'max_data_doi_citations')
        files[f'ranking-{catalog}-data-dois.csv']=csv_table(data,score_key='max_data_doi_citations')
    put_json('overlap-candidates.json',overlap)
    files['overlap-candidates.csv']=csv_table(overlap,['official_id','community_slug','relations','shared_paper_ids','shared_asset_ids','identity_status'])
    put_json('summary.json',summary)
    input_names=['methodology.json','catalog-fetch.json','official-entries.json','reference-groups.json',
                 'review-a.json','review-b.json','review-c.json','reference-corrections.json',
                 'reference-audit.json','description-review.json','description-audit.json','description-data-audit.json','geography-audit.json',
                 'identity-searches.json','title-matches.json','openalex-works.json',
                 'doi-resolution.json','display-labels.json','supplemental-identities.json',
                 'leaders-review.json','post-review-identities.json','final-validation-findings.json',
                 'draft-top15-before-final-reference-review.json']
    input_paths=[HERE/name for name in input_names if (HERE/name).exists()]
    input_paths += sorted((HERE/'responses').glob('*.json'))
    input_paths += [ROOT/'research/citations/rankings.json',ROOT/'research/gee-community-audit-20261029/families.json']
    put_json('input-manifest.json',{str(p.relative_to(ROOT)):hashlib.sha256(p.read_bytes()).hexdigest() for p in input_paths})
    # Plain Markdown report is generated from the same evidence as machine tables.
    lines=['# Official and community GEE citation comparison','',
        'Snapshot: 2026-10-30 (America/Denver). Counts retrieved '+min(times)+' through '+max(times)+'.','',
        'Rankings cover resolved, reviewed references. They are not an exhaustive claim about all citations to a dataset. The score is the maximum citation count of an associated paper; data DOI counts stay separate. Unknown is not zero.','',
        f'Official: {len(official):,} Collection entries, {summary["official"]["deprecated"]:,} deprecated; {summary["official"]["paper_count"]:,} with paper counts, {summary["official"]["data_doi_count"]:,} with data-DOI counts, {summary["official"]["no_count"]:,} without either. Community: 363 documentation families, {summary["community"]["paper_count"]} with paper counts. Population units differ.','',
        'Active-only means not explicitly marked deprecated in this official snapshot; community deprecation was not assessed. Global can include a worldwide land/ocean product with latitude limits, shown in region notes.', '',
        'Final semantic review corrected a generic SPEI index citation, inconsistent report/method roles and several region labels. These post-scoring corrections and the rejected draft are retained in `final-validation-findings.json`; the initial reviews and scoring criteria were committed before counts.','',
        'The original community study and PNG remain unchanged. This comparison refreshes its reviewed work identities into the same observation window as the official study.','']
    labels=read('display-labels.json') if (HERE/'display-labels.json').exists() else {}
    for title,rows in [('Official: top 10 shared-paper groups',official),('Official: top 10 global shared-paper groups',[r for r in official if r['geographic_scope']=='global']),('Official: top 10 without deprecated entries',[r for r in official if r['deprecated'] is not True]),('Combined: top 10 shared-paper groups',combined)]:
        lines += ['## '+title,'','Each group appears once using its leading paper. Entries remain distinct in the CSVs; shared papers are not proof of equivalent datasets. Views include deprecated versions unless the heading excludes them.','', '| Rank | Dataset / paper group | Region | Citations | Catalog | Official GEE status |','|---:|---|---|---:|---|---|']
        for i,g in enumerate(paper_groups(rows)[:10],1):
            rep=g['entries'][0];label=labels.get(norm(g['top_paper_doi'] or ''),rep['title'])
            regions='; '.join(g['regions']);regions=regions if len(regions)<160 else 'See linked group members for region details'
            official_members=[e for e in g['entries'] if e['catalog']=='official']
            status=('All entries deprecated' if all(e['deprecated'] for e in official_members) else 'Has active entries') if official_members else 'Not applicable'
            lines.append(f'| {i} | [{label.replace("|","/")}]({markdown_url(rep["url"])}) ([paper]({markdown_url(g["top_paper_doi"] or g["id"])})) | {regions.replace("|","/")} | {g["max_paper_citations"]:,} | {", ".join(g["catalogs"])} | {status} |')
        lines += ['']
    lines += ['## Evidence and reproduction','',
        '- `official-entries.json`: public STAC descriptions, citation fields, bounds, source URLs/hashes and version flags.',
        '- `review-a/b/c.json`, `reference-corrections.json`, `title-matches.json`: reference roles, scope, corrections and reviewed identities.',
        '- `responses/`, `openalex-works.json`, `doi-resolution.json`: exact requests, timestamps, provider observations and missing references.',
        '- `ranking-*.csv`: complete entry rankings; `groups-*.json/csv`: shared-paper views; data DOI tables remain separate.',
        '- `overlap-candidates.json/csv`: shared papers and exact asset-reference intersections, not automatic equivalence merges.',
        '- `methodology.json`: criteria and cost bounds committed before scoring. `validation.json`: verification receipt.','',
        'Offline rebuild/check (standard-library Python 3.11+):','',
        '```sh','python3 scripts/rank_catalog_citations.py --check','python3 -m unittest discover -s tests -p test_catalog_citations.py','```','',
        'For a new dated snapshot, update the study constants and methodology first, run `capture_official_catalog.py --fetch --normalize`, review identities and geography, then opt into `fetch_catalog_citations.py --identities` / `--counts`. Cached requests are reused. Never overwrite a published snapshot. Full raw STAC is local-only; committed normalized metadata is sufficient for offline scoring.','',
        'Citation rank does not establish a Source Cooperative gap. Before conversion: check the exact release, license, maintained native host, existing registry entries, storage cost and reproducibility. No dataset conversions, live GEE jobs, uploads or registry submissions ran in this study.','']
    files['README.md']='\n'.join(lines)
    for name,body in files.items():
        path=HERE/name
        if args.check:assert path.read_text()==body,'Stale output: '+name
        else:path.write_text(body)
    print(json.dumps(summary,indent=2))
    print('Offline outputs match' if args.check else f'Wrote {len(files)} outputs')

if __name__=='__main__':main()
